// Generated outputs are never hand-edited: `pnpm gen:const-index` rewrites
// both, and `pnpm gen:const-index:check` fails when either has drifted.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_PATH = 'packages/config/CONSTANTS.md';
const MAP_PATH = 'packages/config/const-index.json';

const listConstFiles = (dir) => {
  try {
    return readdirSync(join(repoRoot, dir))
      .filter((f) => /\.ts$/.test(f) && !/\.test\.ts$/.test(f))
      .filter((f) => f !== 'index.ts')
      .sort()
      .map((f) => `${dir}/${f}`);
  } catch {
    return [];
  }
};

export const listSources = () => {
  const apps = readdirSync(join(repoRoot, 'apps')).sort();
  return [
    ...listConstFiles('packages/config/src/constants').map((file) => ({
      file,
      scope: 'config',
      from: '@blog/config/constants',
    })),
    ...listConstFiles('packages/db/src/constants').map((file) => ({
      file,
      scope: 'db',
      from: '@blog/db/constants',
    })),
    ...apps.flatMap((app) =>
      listConstFiles(`apps/${app}/src/constants`).map((file) => ({
        file,
        scope: `app:${app}`,
        from: `@${app}/constants/${basename(file, '.ts')}`,
      })),
    ),
  ];
};

const literalValue = (node) => {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
    return node.text;
  }
  if (ts.isNumericLiteral(node)) {
    return Number(node.text);
  }
  return undefined;
};

const isAsConst = (node) =>
  ts.isAsExpression(node) &&
  ts.isTypeReferenceNode(node.type) &&
  node.type.typeName.getText() === 'const';

export const extractConsts = (fileName, text) => {
  const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true);
  const consts = [];
  for (const stmt of sf.statements) {
    const isExported = stmt.modifiers?.some(
      (m) => m.kind === ts.SyntaxKind.ExportKeyword,
    );
    if (!ts.isVariableStatement(stmt) || !isExported) {
      continue;
    }
    for (const decl of stmt.declarationList.declarations) {
      const init = decl.initializer;
      if (!ts.isIdentifier(decl.name) || !init || !isAsConst(init)) {
        continue;
      }
      if (!ts.isObjectLiteralExpression(init.expression)) {
        continue;
      }
      const members = init.expression.properties.flatMap((prop) => {
        if (!ts.isPropertyAssignment(prop) || !ts.isIdentifier(prop.name)) {
          return [];
        }
        const value = literalValue(prop.initializer);
        return value === undefined ? [] : [{ key: prop.name.text, value }];
      });
      if (members.length > 0) {
        consts.push({ name: decl.name.text, members });
      }
    }
  }
  return consts;
};

const formatMember = ({ key, value }) =>
  key === value ? `\`${key}\`` : `\`${key}\`=\`${JSON.stringify(value)}\``;

export const buildOutputs = (sources, readSource) => {
  const strings = {};
  const numbers = {};
  const lines = [
    '# Const index',
    '',
    '<!-- Generated by scripts/gen-const-index.mjs — run `pnpm gen:const-index`, never hand-edit. -->',
    '',
    'Every key/value const an agent should reuse before writing a literal. The',
    '`prefer-shared-constant` lint rule reads `const-index.json`, generated alongside.',
  ];
  let currentScope;
  for (const source of sources) {
    const consts = extractConsts(source.file, readSource(source.file));
    if (consts.length === 0) {
      continue;
    }
    if (source.scope !== currentScope) {
      currentScope = source.scope;
      lines.push('', `## ${source.scope}`);
    }
    lines.push('', `### \`${source.from}\` — \`${source.file}\``, '');
    for (const { name, members } of consts) {
      lines.push(`- **${name}**: ${members.map(formatMember).join(', ')}`);
      for (const { key, value } of members) {
        const bucket = typeof value === 'number' ? numbers : strings;
        const entry = {
          ref: `${name}.${key}`,
          scope: source.scope,
          from: source.from,
          file: source.file,
        };
        (bucket[String(value)] ??= []).push(entry);
      }
    }
  }
  return {
    catalog: `${lines.join('\n')}\n`,
    map: `${JSON.stringify({ strings, numbers }, null, 2)}\n`,
  };
};

const readRepoFile = (file) => readFileSync(join(repoRoot, file), 'utf8');

const readOrEmpty = (file) => {
  try {
    return readRepoFile(file);
  } catch {
    return '';
  }
};

const main = () => {
  const { catalog, map } = buildOutputs(listSources(), readRepoFile);
  if (!process.argv.includes('--check')) {
    writeFileSync(join(repoRoot, CATALOG_PATH), catalog);
    writeFileSync(join(repoRoot, MAP_PATH), map);
    return;
  }
  const drifted = [
    [CATALOG_PATH, catalog],
    [MAP_PATH, map],
  ].filter(([file, expected]) => readOrEmpty(file) !== expected);
  if (drifted.length > 0) {
    console.error(
      `Const index drift in ${drifted.map(([file]) => file).join(', ')} — run \`pnpm gen:const-index\` and commit the result.`,
    );
    process.exit(1);
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
