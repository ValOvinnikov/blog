// The generated module is never hand-edited: `pnpm gen:migration-ids` rewrites
// it, and `pnpm gen:migration-ids:check` fails when it has drifted.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  listMigrationIds,
  sortMigrationIds,
} from '../packages/studio/scripts/migrate-lib.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS_DIR = 'packages/studio/migrations';
const OUTPUT_PATH = 'packages/config/src/sanity/studio-migration-ids.ts';

export const buildModule = (ids) => {
  const header =
    '// Generated by scripts/gen-migration-ids.mjs — run `pnpm gen:migration-ids`, never hand-edit.';
  if (ids.length === 0) {
    return [
      header,
      'export const STUDIO_MIGRATION_IDS = [] as const;',
      '',
    ].join('\n');
  }
  return [
    header,
    'export const STUDIO_MIGRATION_IDS = [',
    ...sortMigrationIds(ids).map((id) => `  '${id}',`),
    '] as const;',
    '',
  ].join('\n');
};

const readOrEmpty = (file) => {
  try {
    return readFileSync(join(repoRoot, file), 'utf8');
  } catch {
    return '';
  }
};

const main = () => {
  const expected = buildModule(
    listMigrationIds(join(repoRoot, MIGRATIONS_DIR)),
  );
  if (!process.argv.includes('--check')) {
    writeFileSync(join(repoRoot, OUTPUT_PATH), expected);
    return;
  }
  if (readOrEmpty(OUTPUT_PATH) !== expected) {
    console.error(
      `Migration id list drift in ${OUTPUT_PATH} — run \`pnpm gen:migration-ids\` and commit the result.`,
    );
    process.exit(1);
  }
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
