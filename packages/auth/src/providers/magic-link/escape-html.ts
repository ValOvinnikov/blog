// Shared by the magic-link email builders, whose `url` and, for invites,
// tenant names are interpolated into HTML without prior sanitization.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
