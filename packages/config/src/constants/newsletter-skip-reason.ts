import type { TValueOf } from '@shinefold/config/utils';

export const NEWSLETTER_SKIP_REASON = {
  OVER_SUBSCRIBER_BAND: 'OVER_SUBSCRIBER_BAND',
  OVER_MONTHLY_ALLOWANCE: 'OVER_MONTHLY_ALLOWANCE',
  REPUTATION_STOP: 'REPUTATION_STOP',
  SITE_PAUSED: 'SITE_PAUSED',
  NOT_IN_PLAN: 'NOT_IN_PLAN',
  SITE_INACTIVE: 'SITE_INACTIVE',
  NEWSLETTER_OFF: 'NEWSLETTER_OFF',
  SENDING_OFF: 'SENDING_OFF',
} as const;

export type TNewsletterSkipReason = TValueOf<typeof NEWSLETTER_SKIP_REASON>;

// Checked in this order; the first that applies is the cause.
export const NEWSLETTER_SENDING_OFF_CAUSES = [
  NEWSLETTER_SKIP_REASON.NOT_IN_PLAN,
  NEWSLETTER_SKIP_REASON.SITE_INACTIVE,
  NEWSLETTER_SKIP_REASON.NEWSLETTER_OFF,
  NEWSLETTER_SKIP_REASON.SENDING_OFF,
] as const satisfies readonly TNewsletterSkipReason[];

export type TNewsletterSendingOffCause =
  (typeof NEWSLETTER_SENDING_OFF_CAUSES)[number];

export const NEWSLETTER_HAND_SENDABLE_SKIP_REASONS = [
  NEWSLETTER_SKIP_REASON.OVER_SUBSCRIBER_BAND,
  NEWSLETTER_SKIP_REASON.OVER_MONTHLY_ALLOWANCE,
  NEWSLETTER_SKIP_REASON.NEWSLETTER_OFF,
  NEWSLETTER_SKIP_REASON.SENDING_OFF,
] as const satisfies readonly TNewsletterSkipReason[];
