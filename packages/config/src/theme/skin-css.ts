import { isOneOf, objectKeys } from '@shinefold/utils/primitives';

import {
  COLOR_SCHEME,
  PRESET_ID,
  PRESET_REGISTRY,
  SKIN_MODE,
  type TColorScheme,
} from '@shinefold/config/constants';

import { LOGO_TILE_RAMP_DARK } from './accent-ramps';
import { AMBIENT, TOKEN_ALIASES } from './contrast-surfaces';
import { formatPaletteDeclarations } from './palette-ramps';
import { effectiveSchemeOf } from './skin-contrast';
import { isBrandStop } from './skin-derive';
import { paletteStopOf, SKIN_ROLES, type TSkinRoles } from './skin-roles';
import {
  SKIN_REGISTRY,
  SKINS_WITH_STORYBOOK,
  STORYBOOK_SKINS,
  type TSkin,
} from './skins';

export const SKIN_CSS_REPO_PATH = 'configs/tailwind/skins.css';

export const STORYBOOK_SKIN_CSS_REPO_PATH =
  'configs/tailwind/skins-storybook.css';

type TSkins = Record<string, TSkin>;

const DEFAULT_SKIN_HUE =
  PRESET_REGISTRY[PRESET_ID.CONSOLE].themeTokens.accentHue;

const HEADER = `/* Generated by \`pnpm --filter @shinefold/config gen:skins\`; never edit by hand. */`;

const skinSelector = (key: string): string => `[data-skin='${key}']`;

const formatBlock = (selector: string, declarations: string[]): string[] => [
  `${selector} {`,
  ...declarations.map((declaration) => `  ${declaration};`),
  '}',
  '',
];

const SKIN_ROLE_ALIASES = Object.entries(TOKEN_ALIASES).filter(
  ([alias, target]) =>
    !isOneOf(SKIN_ROLES, alias) && isOneOf(SKIN_ROLES, target),
);

const roleDeclarations = (roles: TSkinRoles): string[] =>
  [...SKIN_ROLES.map((role) => [role, roles[role]]), ...SKIN_ROLE_ALIASES].map(
    ([property, token]) => `${property}: var(${token})`,
  );

// 10% lifts the tint off a brand ground by ~1.13:1 light / ~1.16:1 dark while brand-primary-hover text on it holds ≥5.86:1 / ≥5.11:1 across hues.
const BRAND_GROUND_FILLS = [
  '--tint: color-mix(in oklch, var(--backdrop), var(--brand-primary) 10%)',
  '--media-fill: var(--tint)',
  '--item-fill: var(--brand-primary-wash)',
  '--item-nested-fill: var(--surface)',
];

const groundFillDeclarations = (roles: TSkinRoles): string[] =>
  isBrandStop(roles[AMBIENT]) ? BRAND_GROUND_FILLS : [];

// Only a scope that flips the page's scheme re-declares the tile: one that matches keeps the tenant's logo hue from :root or .dark.
const logoTileDeclarations = (
  effectiveScheme: TColorScheme,
  scheme: TColorScheme,
): string[] =>
  effectiveScheme === scheme
    ? []
    : objectKeys(LOGO_TILE_RAMP_DARK).map(
        (token) => `${token}: var(${paletteStopOf(token, effectiveScheme)})`,
      );

const scopeBlock = (
  key: string,
  { mode, roles }: TSkin,
  scheme: TColorScheme,
): string[] => {
  const effectiveScheme = effectiveSchemeOf(mode, scheme);

  return formatBlock(
    scheme === COLOR_SCHEME.DARK
      ? `.dark ${skinSelector(key)}`
      : skinSelector(key),
    [
      `color-scheme: ${effectiveScheme.toLowerCase()}`,
      ...roleDeclarations(roles[scheme]),
      ...groundFillDeclarations(roles[scheme]),
      ...logoTileDeclarations(effectiveScheme, scheme),
    ],
  );
};

const formatSkinScopes = (skins: TSkins): string[] =>
  Object.entries(skins).flatMap(([key, skin]) =>
    Object.values(COLOR_SCHEME).flatMap((scheme) =>
      scopeBlock(key, skin, scheme),
    ),
  );

const formatDarkVariant = (skins: TSkins): string[] => {
  const inverseSelectors = Object.entries(skins)
    .filter(([, { mode }]) => mode === SKIN_MODE.INVERSE)
    .flatMap(([key]) => [skinSelector(key), `${skinSelector(key)} *`]);

  return [
    `@custom-variant dark (&:where(${['.dark', '.dark *', ...inverseSelectors].join(', ')}));`,
    '',
  ];
};

const formatPalette = (): string[] =>
  formatBlock(
    ':root',
    Object.entries(formatPaletteDeclarations(DEFAULT_SKIN_HUE)).map(
      ([property, value]) => `${property}: ${value}`,
    ),
  );

export const formatSkinCss = (): string =>
  [
    HEADER,
    '',
    ...formatDarkVariant(SKIN_REGISTRY),
    ...formatPalette(),
    ...formatSkinScopes(SKIN_REGISTRY),
  ].join('\n');

export const formatStorybookSkinCss = (): string =>
  [
    HEADER,
    '',
    ...formatDarkVariant(SKINS_WITH_STORYBOOK),
    ...formatSkinScopes(STORYBOOK_SKINS),
  ].join('\n');
